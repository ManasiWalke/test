def contains_harmful_content(text: str) -> bool:
    lower = text.lower()
    return any(kw in lower for kw in BLOCKED_KEYWORDS)


def sanitize_output(text: str) -> str:
    """Strip potential PII patterns (emails, phone numbers)."""
    text = re.sub(r'\b[\w.+-]+@[\w-]+\.[a-z]{2,}\b', '[email redacted]', text, flags=re.I)
    text = re.sub(r'\b\+?[\d\s\-().]{10,15}\b', '[phone redacted]', text)
    return text


