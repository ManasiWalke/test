def contains_harmful_content(text: str) -> bool:
    """Guardrail: detect harmful keywords."""
    lower = text.lower()
    return any(kw in lower for kw in BLOCKED_KEYWORDS)


def build_nutrition_prompt(user: dict) -> str:
    """
    Construct a structured, ethics-aware prompt for IBM Granite.
    HAM tone: Helpful, Accurate, Mindful.
    """
    conditions = user.get("medical_history", "None reported")
    diet_label = "Vegetarian" if user.get("diet") == "veg" else "Non-Vegetarian"

    prompt = f"""You are NutriGuide, a compassionate and professional AI nutrition assistant.
Your role is to generate safe, evidence-based, culturally sensitive nutrition plans.
You MUST follow these guidelines:
- Be helpful, respectful, and empathetic (HAM principles).
- Never recommend unsafe diets, extreme fasting, or harmful substances.
- Consider local food availability and cultural preferences.
- Adjust all recommendations for any stated medical conditions.
- If a medical condition requires specialist intervention, say so clearly.

USER PROFILE:
- Name: {user.get("name", "User")}
- Age: {user.get("age", "Unknown")} years
- Diet Preference: {diet_label}
- Medical History: {conditions}
- Location: {user.get("city", "Unknown")}, {user.get("country", "Unknown")}

TASK:
Generate a detailed, personalized 7-day nutrition plan for {user.get("name", "this user")}.
Include:
1. Daily calorie target (with justification based on age and health conditions)
2. Macronutrient breakdown (carbs, proteins, fats)
3. A sample daily meal plan (Breakfast, Mid-Morning Snack, Lunch, Afternoon Snack, Dinner)
4. Key foods to INCLUDE and AVOID given the medical history
5. Hydration guidance
6. 3–5 practical nutrition tips tailored to their location/culture
7. When to seek professional medical advice

Keep the tone warm, encouraging, and professional. Format clearly with headings and bullet points.

NUTRITION PLAN:"""
    return prompt


def build_query_prompt(user_query: str, context: dict) -> str:
    """Prompt for general nutrition Q&A agent."""
    name = context.get("name", "User")
    conditions = context.get("medical_history", "None")

    prompt = f"""You are NutriGuide, a knowledgeable and empathetic AI nutrition assistant.
Answer the following nutrition-related question helpfully, accurately, and safely.
User context — Name: {name}, Medical History: {conditions}.
Never provide harmful, dangerous, or medically irresponsible advice.
If the question is outside nutrition/health, politely redirect.

QUESTION: {user_query}

ANSWER:"""
    return prompt


def call_granite(prompt: str) -> str:
    """Invoke IBM Granite model and return generated text."""
    try:
        response = model.generate_text(prompt=prompt)
        return response.strip() if isinstance(response, str) else str(response)
    except Exception as e:
        return f"⚠️ AI service temporarily unavailable. Please try again. (Error: {str(e)[:120]})"


