@app.route("/api/generate-plan", methods=["POST"])
def generate_plan():
    """Agent endpoint: collect user details → generate nutrition plan."""
    data = request.get_json(force=True)

    # Input validation
    required = ["name", "age", "diet", "city", "country"]
    missing   = [f for f in required if not data.get(f)]
    if missing:
        return jsonify({"error": f"Missing required fields: {', '.join(missing)}"}), 400

    # Guardrail check on input
    combined_input = " ".join(str(v) for v in data.values())
    if contains_harmful_content(combined_input):
        return jsonify({
            "error": "Your input contains content that cannot be processed. "
                     "Please consult a healthcare professional directly."
        }), 400

    prompt = build_nutrition_prompt(data)
    plan   = call_granite(prompt)

    # Guardrail check on output
    if contains_harmful_content(plan):
        plan = ("I'm sorry, but I'm unable to provide a recommendation for this request. "
                "Please consult a registered dietitian or healthcare provider.")

    plan += MEDICAL_DISCLAIMER

    return jsonify({
        "plan":  plan,
        "user":  data.get("name"),
        "agent": "NutriGuide — IBM Granite AI"
    })


@app.route("/api/query", methods=["POST"])
def answer_query():
    """Agentic Q&A endpoint for common nutrition questions."""
    data         = request.get_json(force=True)
    user_query   = data.get("query", "").strip()
    user_context = data.get("context", {})

    if not user_query:
        return jsonify({"error": "Query cannot be empty."}), 400

    if contains_harmful_content(user_query):
        return jsonify({
            "answer": "⚠️ That topic falls outside safe nutritional guidance. "
                      "Please reach out to a qualified healthcare professional."
        })

    prompt = build_query_prompt(user_query, user_context)
    answer = call_granite(prompt)

    if contains_harmful_content(answer):
        answer = ("I'm unable to provide guidance on that topic. "
                  "Please consult a licensed dietitian or physician.")

    answer += "\n\n*— NutriGuide AI | Powered by IBM Granite*"
    return jsonify({"answer": answer})


