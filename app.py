@app.route("/api/approvals/<int:approval_id>", methods=["PATCH"])
def update_approval(approval_id: int):
    """Approve or reject a generated content item."""
    data   = request.get_json(force=True)
    action = data.get("action", "").lower()  # "approve" or "reject"

    if action not in ("approve", "reject"):
        return jsonify({"error": "Action must be 'approve' or 'reject'."}), 400

    item = next((a for a in PENDING_APPROVALS if a["id"] == approval_id), None)
    if not item:
        return jsonify({"error": "Approval item not found."}), 404

    item["status"]   = "approved" if action == "approve" else "rejected"
    item["reviewed"] = datetime.datetime.utcnow().isoformat() + "Z"

    return jsonify({
        "message": f"Content #{approval_id} has been {item['status']}.",
        "item":    item
    })


