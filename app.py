@app.route("/api/generate-content", methods=["POST"])
def generate_content():
    """Main agent: collect brand details → generate full social media content package."""
    data = request.get_json(force=True)

    required = ["brand_name", "industry", "audience", "platforms", "tone", "goals"]
    missing  = [f for f in required if not data.get(f)]
    if missing:
        return jsonify({"error": f"Missing required fields: {', '.join(missing)}"}), 400

    combined = " ".join(str(v) for v in data.values())
    if contains_harmful_content(combined):
        return jsonify({
            "error": "Input contains content that violates ethical AI guidelines. "
                     "Please revise your inputs and try again."
        }), 400

    prompt  = build_content_prompt(data)
    content = call_granite(prompt)

    if contains_harmful_content(content):
        content = ("I'm unable to generate content for this request as it may violate "
                   "ethical guidelines. Please refine your brand profile inputs.")

    # Add to approval queue
    approval_item = {
        "id":        len(PENDING_APPROVALS) + 1,
        "brand":     data.get("brand_name"),
        "timestamp": datetime.datetime.utcnow().isoformat() + "Z",
        "status":    "pending",
        "content":   content[:500] + "..." if len(content) > 500 else content,
        "full_content": content
    }
    PENDING_APPROVALS.append(approval_item)

    content += ETHICS_DISCLAIMER
    return jsonify({
        "content":    content,
        "brand":      data.get("brand_name"),
        "approval_id": approval_item["id"],
        "agent":      "SocialMind — IBM Granite AI",
        "status":     "pending_approval"
    })


